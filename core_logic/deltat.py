def _tidal(ans: float, year: float) -> float:
    return ans - 0.000091 * (TIDAL_DE431 - TIDAL_TABLE) * (year - 1955.0) ** 2 if year < 1955.0 else ans


def deltat_se202(jd_ut: float) -> float:
    """Delta-T in days as Swiss Ephemeris 2.02 computes it (swe_deltat).

    Before JD 2317746.13 (1633.7) the polynomials of Espenak & Meeus 2006 (NASA TP-2006-214141); to the end of the
    table the table; after it Stephenson's parabola (-20 + 31 t^2, t in centuries from 1820), blended into the
    table's last value over 100 years.
    """
    year = 2000.0 + (jd_ut - J2000) / 365.2425
    if jd_ut < 2317746.130902778:
        if year < -500:
            ans = 32.0 * ((year - 1820.0) / 100.0) ** 2 - 20.0
        elif year < 500:
            u = year / 100.0
            ans = (((((0.0090316521 * u + 0.022174192) * u - 0.1798452) * u - 5.952053) * u + 33.78311) * u
                   - 1014.41) * u + 10583.6
        elif year < 1600:
            u = (year - 1000.0) / 100.0
            ans = (((((0.0083572073 * u - 0.005050998) * u - 0.8503463) * u + 0.319781) * u + 71.23472) * u
                   - 556.01) * u + 1574.2
        else:
            u = year - 1600.0
            ans = 120.0 - 0.9808 * u - 0.01532 * u * u + u ** 3 / 7129.0
        return _tidal(ans, year) / 86400.0
    n = len(DT)
    tabend = TABLE_START + n - 1
    if year > tabend:
        ans = -20.0 + 31.0 * ((year - 1820.0) * 0.01) ** 2
        if year < tabend + 100:
            ans += (year - (tabend + 100)) * (-20.0 + 31.0 * ((tabend - 1820) * 0.01) ** 2 - DT[-1]) * 0.01
        return ans / 86400.0
    p = math.floor(year)
    iy = int(p - TABLE_START)
    ans = DT[iy]
    if iy + 1 < n:
        p = year - p
        ans += p * (DT[iy + 1] - DT[iy])
        if iy - 1 >= 0 and iy + 2 < n:
            d = [0.0 if (k < 0 or k + 1 >= n) else DT[k + 1] - DT[k] for k in range(iy - 2, iy + 3)]
            d = [d[i + 1] - d[i] for i in range(4)]                       # second differences
            b = 0.25 * p * (p - 1.0)
            ans += b * (d[1] + d[2])
            d = [d[i + 1] - d[i] for i in range(3)]                       # third
            b = 2.0 * b / 3.0
            ans += (p - 0.5) * b * d[1]
            if iy - 2 >= 0 and iy + 3 <= n:
                d = [d[i + 1] - d[i] for i in range(2)]                   # fourth
                b = 0.125 * b * (p + 1.0) * (p - 2.0)
                ans += b * (d[0] + d[1])
    return _tidal(ans, year) / 86400.0
