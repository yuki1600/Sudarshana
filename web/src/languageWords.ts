const loaded = new Map<Code, Words>();

/** The language's lookup: the rows, then the grahas' and signs' names as the charts write them, then each tithi with its paksha. */
export function wordsFor(code: Code): Words {
  const kept = loaded.get(code);
  if (kept) return kept;
  const w = build(code, [ROWS, CORE, UI, TITHIS].join("\n"), GRAMMAR[code], VERBS);
  const chart = CHART_LABELS[LANGUAGES.find((l) => l.code === code)!.id]!;
  KEYS.forEach((k, i) => {
    add(w, k, chart.bodies[i], true);
    if (i > 0 && i < 13) add(w, k + "R", chart.bodies[i] + chart.retro, true);     // the server's SaR
  });
  add(w, "(R)", chart.retro);
  SIGN_KEYS.forEach((keys, s) => {
    for (const k of keys.split(";")) add(w, k, chart.signs[s]);
    add(w, SIGN_ABBR[s], chart.signs[s], true);
  });
  // "Sukla Panchami", "Krishna Ashtami": the paksha, then the tithi
  const [sukla, krishna] = PAKSHA[code];
  for (const line of TITHIS.split("\n")) {
    if (!line.trim()) continue;
    const names = line.split("|")[0].split(";"), tithi = translate(w, names[0]);
    for (const n of names) for (const [p, v] of [["Sukla", sukla], ["Shukla", sukla], ["Krishna", krishna]]) add(w, `${p} ${n}`, `${v} ${tithi}`);
  }
  loaded.set(code, w);
  return w;
}
