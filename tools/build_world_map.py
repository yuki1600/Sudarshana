"""Writes web/src/worldMap.ts: Natural Earth's land, lakes, borders and state lines as SVG paths in degrees (x = longitude, y = latitude), and its cities.

python tools/build_world_map.py <folder>
with these from github.com/nvkelso/natural-earth-vector, geojson/: ne_10m_land, ne_50m_lakes, ne_10m_admin_0_boundary_lines_land,
ne_10m_admin_1_states_provinces_lines, ne_10m_populated_places_simple
"""
import json
import os
import sys

OUT = os.path.join(os.path.dirname(__file__), "..", "web", "src", "worldMap.ts")
TOLERANCE = 0.04          # degrees: under 2 px at the map's closest zoom
MIN_LAND, MIN_LAKE = 0.02, 0.1      # square degrees
STATE_ZOOM = 6.7          # Natural Earth's own level: states and provinces, not the counties further down
INTERNATIONAL = "International boundary (verify)"
NOT_BORDERS = {"Overlay limit", "Lease limit"}


def simplify(line, tolerance=TOLERANCE):
    """Douglas-Peucker; a closed ring keeps its first point."""
    keep = {0, len(line) - 1}
    stack = [(0, len(line) - 1)]
    while stack:
        a, b = stack.pop()
        (x0, y0), (x1, y1) = line[a][:2], line[b][:2]
        dx, dy, far, at = x1 - x0, y1 - y0, 0.0, None
        norm = dx * dx + dy * dy
        for i in range(a + 1, b):
            x, y = line[i][:2]
            d = (dy * (x - x0) - dx * (y - y0)) ** 2 / norm if norm else (x - x0) ** 2 + (y - y0) ** 2
            if d > far:
                far, at = d, i
        if far > tolerance * tolerance:
            keep.add(at)
            stack += [(a, at), (at, b)]
    return [line[i] for i in sorted(keep)]


def area(ring):
    return abs(sum(p[0] * q[1] - q[0] * p[1] for p, q in zip(ring, ring[1:]))) / 2


def path(line, close=""):
    points = []
    for lon, lat in (p[:2] for p in simplify(line)):
        p = "%g %g" % (round(lon, 2), round(lat, 2))
        if not points or points[-1] != p:
            points.append(p)
    return "M" + "L".join(points) + close if len(points) > 1 else ""


def parts(geometry):
    kind, c = geometry["type"], geometry["coordinates"]
    return [c] if kind == "LineString" else c if kind in ("MultiLineString", "Polygon") else [ring for polygon in c for ring in polygon]


def load(folder, name):
    with open(os.path.join(folder, name + ".geojson"), encoding="utf-8") as f:
        return [g for g in json.load(f)["features"] if g["geometry"]]


def main(folder):
    assert simplify([[0, 0], [1, 0.001], [2, 0]]) == [[0, 0], [2, 0]] and simplify([[0, 0], [1, 1], [2, 0]]) == [[0, 0], [1, 1], [2, 0]]
    rings = lambda features, least: "".join(path(r, "Z") for g in features for r in parts(g["geometry"]) if area(r) >= least)
    lines = lambda features: "".join(path(r) for g in features for r in parts(g["geometry"]))
    borders = [g for g in load(folder, "ne_10m_admin_0_boundary_lines_land") if g["properties"]["FEATURECLA"] not in NOT_BORDERS]
    states = [g for g in load(folder, "ne_10m_admin_1_states_provinces_lines")
              if g["properties"]["MIN_ZOOM"] <= STATE_ZOOM and g["properties"]["FEATURECLA"] != "Unrecognized Admin-1 boundary"]
    cities = [g["properties"] for g in load(folder, "ne_10m_populated_places_simple")]
    # the biggest first: the map shows more of the list the closer it is, and where labels collide the first keeps its name
    cities.sort(key=lambda c: (c["scalerank"], -c["pop_max"]))
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/build_world_map.py from Natural Earth: degrees, y is north.\n")
        f.write('export const LAND = "%s";\n' % rings(load(folder, "ne_10m_land"), MIN_LAND))
        f.write('export const LAKES = "%s";\n' % rings(load(folder, "ne_50m_lakes"), MIN_LAKE))
        f.write('export const BORDERS = "%s";\n' % lines(g for g in borders if g["properties"]["FEATURECLA"] == INTERNATIONAL))
        f.write("// disputed, indefinite, lines of control: Natural Earth's default view, the lines as they stand\n")
        f.write('export const DISPUTED = "%s";\n' % lines(g for g in borders if g["properties"]["FEATURECLA"] != INTERNATIONAL))
        f.write('export const STATES = "%s";\n' % lines(states))
        f.write("// name, country, latitude, longitude, the biggest first\n")
        f.write("export const CITIES: [string, string, number, number][] = %s;\n" % json.dumps(
            [[c["name"], c["adm0name"] if c["iso_a2"] == "-99" else c["iso_a2"], round(c["latitude"], 2), round(c["longitude"], 2)] for c in cities], ensure_ascii=False, separators=(",", ":")))


if __name__ == "__main__":
    main(sys.argv[1])
